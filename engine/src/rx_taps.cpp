const RxFirTable* rx_fir_v1(double bw_rel) {
    // 相对容差 1e-9：bw_rel 是 bw_Hz / fs 两个 double 相除来的，0.8 这类十进制值
    // 本来就不精确可表示。这是**表示误差的匹配容差**，不是「取最近一档」——
    // 差得更远一律查不到，由调用方报错并列出可取的值（铁律 15）。
    for (std::size_t i = 0; i < sizeof(kRxTables) / sizeof(kRxTables[0]); ++i) {
        const double t = kRxTables[i].bw_rel;
        const double d = bw_rel > t ? bw_rel - t : t - bw_rel;
        if (d <= 1e-9 * t) return &kRxTables[i];
    }
    return 0;
}

