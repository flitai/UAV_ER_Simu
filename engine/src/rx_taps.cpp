void rx_fir_expand(const RxFirTable& t, std::vector<double>& h) {
    // 镜像展开。与 scripts/design_rx_fir.py 的 expand() 逐字同法。
    h.assign(static_cast<std::size_t>(t.ntaps), 0.0);
    const int m = (t.ntaps + 1) / 2;
    for (int k = 0; k < m; ++k) {
        h[static_cast<std::size_t>(k)] = t.half[k];
        h[static_cast<std::size_t>(t.ntaps - 1 - k)] = t.half[k];
    }
}

